import type { VercelRequest, VercelResponse } from "@vercel/node";

const allowedServices = new Set([
  "Landing Page",
  "Starter Website",
  "Standard Website",
  "Advanced Website",
  "E-commerce Website",
  "Custom Website",
  "IT Solutions",
  "Graphic Design & Branding",
]);
const clean = (value: unknown, max = 3000) =>
  typeof value === "string" ? value.trim().slice(0, max) : "";

export default async function handler(req: VercelRequest, res: VercelResponse) {
  res.setHeader("Cache-Control", "no-store");
  if (req.method !== "POST") {
    res.setHeader("Allow", "POST");
    return res.status(405).json({ error: "Method not allowed." });
  }

  const { RESEND_API_KEY, ENQUIRY_FROM_EMAIL, ENQUIRY_TO_EMAIL } = process.env;
  if (!RESEND_API_KEY || !ENQUIRY_FROM_EMAIL || !ENQUIRY_TO_EMAIL) {
    return res
      .status(503)
      .json({
        error:
          "Email delivery is not configured yet. Please use WhatsApp for now.",
      });
  }

  const body =
    typeof req.body === "string" ? JSON.parse(req.body) : (req.body ?? {});
  const name = clean(body.name, 120);
  const email = clean(body.email, 200);
  const phone = clean(body.phone, 80);
  const organisation = clean(body.organisation, 200);
  const service = clean(body.service, 100);
  const packagePrice = clean(body.packagePrice, 100);
  const budget = clean(body.budget, 100);
  const timeline = clean(body.timeline, 100);
  const details = clean(body.details, 5000);

  if (!name || !phone || !details || !allowedServices.has(service)) {
    return res
      .status(400)
      .json({
        error:
          "Please provide your name, phone number, service and project details.",
      });
  }
  if (email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    return res
      .status(400)
      .json({ error: "Please enter a valid email address." });
  }

  const safe = (s: string) =>
    s.replace(
      /[&<>"']/g,
      (ch) =>
        ({
          "&": "&amp;",
          "<": "&lt;",
          ">": "&gt;",
          '"': "&quot;",
          "'": "&#39;",
        })[ch] as string,
    );
  const rows: Array<[string, string]> = [
    ["Name", name],
    ["Email", email || "Not provided"],
    ["Phone / WhatsApp", phone],
    ["Business / organisation", organisation || "Not provided"],
    ["Service", service],
    ["Package price", packagePrice || "Quotation based on requirements"],
    ["Budget", budget || "Not specified"],
    ["Preferred timeline", timeline || "Not specified"],
    ["Project details", details],
  ];
  const html = `<div style="font-family:Arial,sans-serif;color:#1b2540;max-width:680px;margin:auto"><div style="background:#10182b;color:#fff;padding:24px 28px"><p style="margin:0 0 7px;color:#a8adff;font-size:11px;letter-spacing:2px">AYOTECH SOLUTIONS</p><h1 style="font-size:24px;margin:0">New website enquiry</h1></div><div style="padding:24px 28px;border:1px solid #e5e9f2"><p>A new enquiry was submitted through the Ayotech Solutions website.</p><table style="border-collapse:collapse;width:100%">${rows.map(([k, v]) => `<tr><th style="text-align:left;vertical-align:top;padding:11px 12px 11px 0;border-bottom:1px solid #e9edf5;width:180px;font-size:13px">${safe(k)}</th><td style="padding:11px 0;border-bottom:1px solid #e9edf5;font-size:13px;line-height:1.7;white-space:pre-wrap">${safe(v)}</td></tr>`).join("")}</table><p style="color:#7a8497;font-size:11px;margin-top:24px">This message was generated by the Ayotech Solutions website enquiry form.</p></div></div>`;

  try {
    const result = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${RESEND_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        from: ENQUIRY_FROM_EMAIL,
        to: [ENQUIRY_TO_EMAIL],
        reply_to: email || undefined,
        subject: `Website enquiry: ${service} — ${name}`,
        html,
        text: rows.map(([k, v]) => `${k}:\n${v}`).join("\n\n"),
      }),
    });
    const payload = await result.json().catch(() => ({}));
    if (!result.ok) {
      console.error("Resend email delivery failed", {
        status: result.status,
        message: payload?.message,
      });
      return res
        .status(502)
        .json({
          error:
            "We could not send your enquiry right now. Please try WhatsApp instead.",
        });
    }
    return res.status(200).json({ ok: true });
  } catch (error) {
    console.error("Enquiry email request failed", error);
    return res
      .status(502)
      .json({
        error:
          "Email delivery could not be reached. Please try WhatsApp instead.",
      });
  }
}
